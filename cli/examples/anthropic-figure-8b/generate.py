#!/usr/bin/env python3
"""Regenerate independently watchable stories from shared renderer, panels, assets."""
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parent
PANELS = json.loads((ROOT/'shared/panels.json').read_text())
RENDERER = (ROOT/'shared/scene.js').read_text()
SOURCE = 'https://www-cdn.anthropic.com/52e1f5d50c47ca3818f56704c27cf19e59b62e77.pdf'
STAGES = [('context', 'Cell, dystroglycan, and coat'), ('antibody', 'Antibody architecture'),
          ('complete', 'Illustrative assembled bridge'), ('contacts', 'Contacts and reach')]
CAVEAT = ('This is a representative reconstruction, with illustrative poses and spacing. '
          'The coat uses a **LAMA2 LG4-5 homolog shape proxy (5IK8 B), not LAMA4**. '
          'IgG/Fab/Fv domains use generic 1HZH scaffolds, not the tool antibody sequences. '
          'Dystroglycan comes from rabbit 9C3C, without the released alpha-DG N-terminal domain. '
          'Contacts are schematic markers, not measured atomic bonds. The paper reports unknown '
          'coat orientation/density and no measured stoichiometry.')

def write_if_changed(path, content):
    # Avoid needless filesystem events and preview reloads on regeneration.
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def story(name, title, panels, scenes):
    out = ROOT/name
    (out/'scenes').mkdir(parents=True, exist_ok=True)
    (out/'assets').mkdir(exist_ok=True)
    for source in (ROOT/'shared/assets').iterdir():
        target = out/'assets'/source.name
        if not target.exists() or target.read_bytes() != source.read_bytes():
            shutil.copy2(source, target)
    code = '// Generated by ../generate.py. Edit ../shared/scene.js and ../shared/panels.json.\n'
    code += 'const panels = '+json.dumps(panels, indent=2)+';\n'+RENDERER
    write_if_changed(out/'story.js', code)
    write_if_changed(out/'story.yaml', 'title: '+json.dumps(title)+'\nauthor_note: "Figure 8b representative reconstruction; template/proxy geometry, illustrative poses"\nscenes:\n'+''.join('  - folder: '+key+'\n' for key,_,_,_ in scenes))
    for key, header, javascript, description in scenes:
        d = out/'scenes'/key
        d.mkdir(exist_ok=True)
        write_if_changed(d/(key+'.yaml'), 'header: '+json.dumps(header)+'\nkey: '+name+'-'+key+'\nlinger_duration_ms: 12000\ntransition_duration_ms: 700\n')
        write_if_changed(d/(key+'.js'), javascript+'\n')
        write_if_changed(d/(key+'.md'), description+'\n\n'+CAVEAT+'\n\n[Source: Figure 8b, p. 14; structural methods, p. 25]('+SOURCE+').\n')

for p in PANELS:
    scenes = []
    for stage, title in STAGES:
        js = f"builder.canvas({{ background_color: '#ffffff' }});\ndrawPanel(panels[0], '{stage}');\nbuilder.camera({{ target: [0, 20, 0], position: [0, 20, 600], up: [0, 1, 0] }});"
        description = '## '+p['title']+' - '+title+'\n\n'+p['subtitle']+'. '+p['explanation']
        if stage == 'contacts': description += '\n\nFilled markers indicate contacts illustrated in the paper. An open marker indicates a possible second LAMA4 contact, not a demonstrated bond.'
        scenes.append((stage, p['title']+' | '+title, js, description))
    story(p['id'], 'Figure 8b | '+p['title'], [p], scenes)

scenes=[]
for stage, title in [('complete','All three formats'),('contacts','Compare contacts and reach')]:
    js = "builder.canvas({ background_color: '#ffffff' });\n"
    js += f"panels.forEach((p, i) => drawPanel(p, '{stage}', (i - 1) * 360));\n"
    js += "builder.camera({ target: [0, 20, 0], position: [0, 20, 1300], up: [0, 1, 0] });"
    scenes.append((stage,title,js,'## Figure 8b - '+title+'\n\nLeft: **1+1 CrossMab**. Center: **2+1**. Right: **2+2 IgG-scFv**. All three panels share the same coordinate scale.'))
story('00-comparison','Figure 8b | Antibody formats side by side',PANELS,scenes)
print('Generated comparison + three independent panel stories.')
